typedef struct renderer_snapshot
{
    SDL_Texture *target;
    SDL_Rect viewport, clip;
    SDL_BlendMode blend;
    Uint8 red, green, blue, alpha;
    float scale_x, scale_y;
    int logical_width, logical_height;
    SDL_bool clipped;
} renderer_snapshot;

/* Damon V. Caskey - 2026-11-15: record public SDL state around explicit capture. */
static renderer_snapshot snapshot_renderer(void)
{
    renderer_snapshot result = { 0 };
    result.target = SDL_GetRenderTarget(renderer);
    SDL_RenderGetViewport(renderer, &result.viewport);
    SDL_RenderGetClipRect(renderer, &result.clip);
    result.clipped = SDL_RenderIsClipEnabled(renderer);
    SDL_RenderGetScale(renderer, &result.scale_x, &result.scale_y);
    SDL_RenderGetLogicalSize(renderer, &result.logical_width, &result.logical_height);
    assert(SDL_GetRenderDrawBlendMode(renderer, &result.blend) == 0);
    assert(SDL_GetRenderDrawColor(renderer, &result.red, &result.green,
                                 &result.blue, &result.alpha) == 0);
    return result;
}

/* Damon V. Caskey - 2026-11-15: compare every state capture promises to restore. */
static void assert_renderer_restored(const renderer_snapshot *expected)
{
    renderer_snapshot actual = snapshot_renderer();
    assert(actual.target == expected->target);
    assert(!memcmp(&actual.viewport, &expected->viewport, sizeof(actual.viewport)));
    assert(!memcmp(&actual.clip, &expected->clip, sizeof(actual.clip)));
    assert(actual.clipped == expected->clipped);
    assert(actual.blend == expected->blend);
    assert(actual.red == expected->red && actual.green == expected->green);
    assert(actual.blue == expected->blue && actual.alpha == expected->alpha);
    assert(actual.scale_x == expected->scale_x && actual.scale_y == expected->scale_y);
    assert(actual.logical_width == expected->logical_width);
    assert(actual.logical_height == expected->logical_height);
}

/* Damon V. Caskey - 2026-11-15: render one texture through real SDL conversion. */
static void read_texture(SDL_Texture *source, uint32_t *pixels, int width, int height)
{
    SDL_Texture *target = SDL_CreateTexture(renderer, SDL_PIXELFORMAT_ABGR8888,
                                           SDL_TEXTUREACCESS_TARGET, width, height);
    SDL_Texture *saved = SDL_GetRenderTarget(renderer);
    assert(target);
    assert(SDL_SetRenderTarget(renderer, target) == 0);
    assert(SDL_RenderSetLogicalSize(renderer, 0, 0) == 0);
    assert(SDL_RenderSetScale(renderer, 1, 1) == 0);
    assert(SDL_RenderSetViewport(renderer, NULL) == 0);
    assert(SDL_RenderSetClipRect(renderer, NULL) == 0);
    assert(SDL_SetTextureBlendMode(source, SDL_BLENDMODE_NONE) == 0);
    assert(SDL_RenderCopy(renderer, source, NULL, NULL) == 0);
    assert(SDL_RenderReadPixels(renderer, NULL, SDL_PIXELFORMAT_ABGR8888,
                                pixels, width * 4) == 0);
    assert(SDL_SetRenderTarget(renderer, saved) == 0);
    SDL_DestroyTexture(target);
}

/* Damon V. Caskey - 2026-11-15: RGB comparisons ignore the unused engine byte. */
static void assert_rgb_equal(const uint32_t *expected, const uint32_t *actual,
                             size_t count)
{
    size_t index;
    for(index = 0; index < count; ++index)
        assert((expected[index] & UINT32_C(0xFFFFFF)) ==
               (actual[index] & UINT32_C(0xFFFFFF)));
}

/* Damon V. Caskey - 2026-11-15: confirm opaque neutral YUV black and white. */
static void assert_shade(const uint32_t *pixels, size_t count, int white)
{
    size_t index;
    for(index = 0; index < count; ++index)
    {
        int red = pixels[index] & 255;
        int green = (pixels[index] >> 8) & 255;
        int blue = (pixels[index] >> 16) & 255;
        if(white) assert(red >= 250 && green >= 250 && blue >= 250);
        else assert(red <= 4 && green <= 4 && blue <= 4);
    }
}

/* Damon V. Caskey - 2026-11-15: sample selection must not raise game hint priority. */
static void test_sampling_hint(void)
{
    SDL_Texture *probe;
    assert(SDL_SetHintWithPriority(SDL_HINT_RENDER_SCALE_QUALITY, "nearest",
                                   SDL_HINT_DEFAULT));
    probe = video_android_movie_texture(4, 4, DC_RESAMPLE_MOVIE);
    assert(probe);
    SDL_DestroyTexture(probe);
    assert(!strcmp(SDL_GetHint(SDL_HINT_RENDER_SCALE_QUALITY), "nearest"));
    assert(SDL_SetHintWithPriority(SDL_HINT_RENDER_SCALE_QUALITY, "linear",
                                   SDL_HINT_DEFAULT));
    assert(SDL_SetHintWithPriority(SDL_HINT_RENDER_SCALE_QUALITY, "nearest",
                                   SDL_HINT_DEFAULT));
}

/* Damon V. Caskey - 2026-11-15: exercise sampler switching and upload identity. */
static void test_movie_upload(gpu_yuv_source *source, unsigned char *luma,
                              uint32_t *linear_reference)
{
    SDL_Texture *game = texture;
    const void *original_owner = source->owner;
    yuv_video_mode mode = { 4, 4, 16, 12 };
    uint32_t pixels[64];
    int row;
    assert(video_setup_yuv_overlay(&mode));
    assert(texture == game && textureWidth == 13 && textureHeight == 9);
    assert(movie_texture && movie_texture != texture);
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, pixels, 8, 8);
    assert_shade(pixels, 64, 0);

    memset(luma, 235, 16);
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, pixels, 8, 8);
    assert_shade(pixels, 64, 0);
    ++source->generation;
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, pixels, 8, 8);
    assert_shade(pixels, 64, 1);

    memset(luma, 16, 16);
    source->owner = &alternate_owner;
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, pixels, 8, 8);
    assert_shade(pixels, 64, 0);
    memset(luma, 235, 16);
    source->owner = original_owner;
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, pixels, 8, 8);
    assert_shade(pixels, 64, 1);

    for(row = 0; row < 4; ++row)
    {
        luma[row * 4] = luma[row * 4 + 1] = 16;
        luma[row * 4 + 2] = luma[row * 4 + 3] = 235;
    }
    ++source->generation;
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, linear_reference, 8, 8);
    assert((linear_reference[3] & 255) > 20);
    assert((linear_reference[3] & 255) < 220);
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_NEAREST));
    read_texture(movie_texture, pixels, 8, 8);
    assert((pixels[3] & 255) <= 4 && (pixels[4] & 255) >= 250);
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, pixels, 8, 8);
    assert_rgb_equal(linear_reference, pixels, 64);

    /* The controller skips setup after external video mode recreation. */
    SDL_DestroyTexture(movie_texture);
    movie_texture = NULL;
    movie_owner = NULL;
    assert(video_prepare_yuv_frame(source, DC_RESAMPLE_MOVIE));
    read_texture(movie_texture, pixels, 8, 8);
    assert_rgb_equal(linear_reference, pixels, 64);

    assert(video_display_yuv_frame());
    assert(presented_texture == movie_texture);
    assert(presented_width == 16 && presented_height == 12);
    assert(texture == game && textureWidth == 13 && textureHeight == 9);
    assert(!video_prepare_yuv_frame(source, DC_RESAMPLE_LANCZOS_3));
    assert(movie_resample == DC_RESAMPLE_MOVIE && texture == game);
}

/* Damon V. Caskey - 2026-11-15: readback restores arbitrary offscreen SDL state. */
static void test_capture(gpu_yuv_source *source, const uint32_t *reference)
{
    SDL_Texture *saved_movie = movie_texture;
    SDL_Texture *state_target = SDL_CreateTexture(renderer, SDL_PIXELFORMAT_ABGR8888,
                                                 SDL_TEXTUREACCESS_TARGET, 40, 32);
    SDL_Rect viewport = { 3, 2, 17, 11 }, clip = { 1, 1, 4, 3 };
    renderer_snapshot expected;
    s_screen *screen = calloc(1, sizeof(*screen) + 64 * sizeof(uint32_t));
    assert(screen && state_target);
    screen->magic = screen_magic;
    screen->pixelformat = PIXEL_32;
    screen->width = screen->height = 8;
    assert(SDL_SetRenderTarget(renderer, state_target) == 0);
    assert(SDL_RenderSetLogicalSize(renderer, 30, 20) == 0);
    assert(SDL_RenderSetScale(renderer, 1.25f, 1.5f) == 0);
    assert(SDL_RenderSetViewport(renderer, &viewport) == 0);
    assert(SDL_RenderSetClipRect(renderer, &clip) == 0);
    assert(SDL_SetRenderDrawBlendMode(renderer, SDL_BLENDMODE_ADD) == 0);
    assert(SDL_SetRenderDrawColor(renderer, 23, 45, 67, 89) == 0);
    expected = snapshot_renderer();

    assert(video_capture_yuv_frame(screen, source, DC_RESAMPLE_MOVIE));
    assert(readbacks == 1);
    assert_rgb_equal(reference, (const uint32_t *)screen->data, 64);
    assert_renderer_restored(&expected);
    assert(movie_texture == saved_movie && textureWidth == 13 && textureHeight == 9);

    assert(!video_capture_yuv_frame(screen, source, DC_RESAMPLE_BICUBIC_MITCHELL));
    assert(readbacks == 1);
    assert_renderer_restored(&expected);

    brightness = 128;
    assert(video_capture_yuv_frame(screen, source, DC_RESAMPLE_NEAREST));
    assert_renderer_restored(&expected);
    assert(((uint32_t *)screen->data)[0] % 256 >= 120);
    assert(((uint32_t *)screen->data)[0] % 256 <= 132);
    brightness = INT_MAX;
    assert(video_capture_yuv_frame(screen, source, DC_RESAMPLE_MOVIE));
    assert_renderer_restored(&expected);
    assert_shade((const uint32_t *)screen->data, 64, 1);
    brightness = INT_MIN;
    assert(video_capture_yuv_frame(screen, source, DC_RESAMPLE_MOVIE));
    assert_renderer_restored(&expected);
    assert_shade((const uint32_t *)screen->data, 64, 0);
    brightness = 0;
    assert(SDL_SetRenderTarget(renderer, NULL) == 0);
    assert(SDL_RenderSetLogicalSize(renderer, 0, 0) == 0);
    assert(SDL_RenderSetScale(renderer, 1, 1) == 0);
    assert(SDL_RenderSetViewport(renderer, NULL) == 0);
    assert(SDL_RenderSetClipRect(renderer, NULL) == 0);
    SDL_DestroyTexture(state_target);
    free(screen);
}

/* Damon V. Caskey - 2026-11-15: higher-priority hints cannot silently change filters. */
static void test_overriding_sampling_hint(void)
{
    SDL_Texture *probe;
    assert(SDL_SetHintWithPriority(SDL_HINT_RENDER_SCALE_QUALITY, "linear",
                                   SDL_HINT_OVERRIDE));
    assert(!video_android_movie_texture(4, 4, DC_RESAMPLE_NEAREST));
    probe = video_android_movie_texture(4, 4, DC_RESAMPLE_MOVIE);
    assert(probe);
    SDL_DestroyTexture(probe);
    assert(!strcmp(SDL_GetHint(SDL_HINT_RENDER_SCALE_QUALITY), "linear"));
    assert(SDL_SetHintWithPriority(SDL_HINT_RENDER_SCALE_QUALITY, "0",
                                   SDL_HINT_OVERRIDE));
    probe = video_android_movie_texture(4, 4, DC_RESAMPLE_NEAREST);
    assert(probe);
    SDL_DestroyTexture(probe);
    assert(!strcmp(SDL_GetHint(SDL_HINT_RENDER_SCALE_QUALITY), "0"));
    assert(SDL_SetHintWithPriority(SDL_HINT_RENDER_SCALE_QUALITY, "1",
                                   SDL_HINT_OVERRIDE));
    probe = video_android_movie_texture(4, 4, DC_RESAMPLE_MOVIE);
    assert(probe);
    SDL_DestroyTexture(probe);
    assert(!strcmp(SDL_GetHint(SDL_HINT_RENDER_SCALE_QUALITY), "1"));
}

/* Damon V. Caskey - 2026-11-15: separate unavailable acceleration from defects. */
int main(void)
{
    SDL_RendererInfo info;
    unsigned char luma[16], chroma[4];
    uint32_t linear_reference[64];
    int owner;
    gpu_yuv_source source = { &owner, 1, 4, 4, luma, chroma, chroma };
    if(SDL_Init(SDL_INIT_VIDEO) < 0)
    {
        fprintf(stderr, "Android adapter host test unavailable: %s\n", SDL_GetError());
        return 77;
    }
    window = SDL_CreateWindow("Android movie adapter", 0, 0, 64, 48, SDL_WINDOW_HIDDEN);
    if(window)
        renderer = SDL_CreateRenderer(window, -1,
                    SDL_RENDERER_ACCELERATED | SDL_RENDERER_TARGETTEXTURE);
    if(!renderer || SDL_GetRendererInfo(renderer, &info) < 0 ||
       !(info.flags & SDL_RENDERER_ACCELERATED))
    {
        fprintf(stderr, "Android adapter host acceleration unavailable: %s\n", SDL_GetError());
        SDL_DestroyRenderer(renderer);
        SDL_DestroyWindow(window);
        SDL_Quit();
        return 77;
    }
    test_sampling_hint();
    texture = SDL_CreateTexture(renderer, SDL_PIXELFORMAT_ABGR8888,
                               SDL_TEXTUREACCESS_STREAMING, 13, 9);
    assert(texture);
    memset(luma, 16, sizeof(luma));
    memset(chroma, 128, sizeof(chroma));
    test_movie_upload(&source, luma, linear_reference);
    test_capture(&source, linear_reference);
    test_overriding_sampling_hint();
    assert(video_restore_mode());
    assert(!movie_texture && !movie_owner && texture);
    assert(textureWidth == 13 && textureHeight == 9);
    assert(!video_display_yuv_frame());
    SDL_DestroyTexture(texture);
    SDL_DestroyRenderer(renderer);
    SDL_DestroyWindow(window);
    SDL_Quit();
    printf("Android movie adapter: accelerated SDL %s, sampler/cache/recreation/capture/state contracts passed (%u explicit readbacks, %u rejection logs).\n",
           info.name, readbacks, rejected_operations);
    return 0;
}
